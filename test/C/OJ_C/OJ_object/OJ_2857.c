#include <stdio.h>

int main() {
    int a, b, c, d;
    
    // 输入当前时、分、秒和学习时长
    scanf("%d", &a);
    scanf("%d", &b);
    scanf("%d", &c);
    scanf("%d", &d);
    
    // 处理秒数加上学习时长
    c += d;  // 先把秒数加到当前的秒数上
    
    // 处理秒数进位
    b += c / 60;  // 将秒数转化为分钟
    c = c % 60;   // 更新秒数
    
    // 处理分钟进位
    a += b / 60;  // 将分钟转化为小时
    b = b % 60;   // 更新分钟
    
    // 处理小时进位，确保小时在1到12之间
    a = (a - 1) % 12 + 1;  // 处理12小时制
    
    // 输出结果
    printf("%d %d %d\n", a, b, c);
    
    return 0;
}
